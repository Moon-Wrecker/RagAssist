"""docs/testing.md is the entry point for the test suite. Its interface appendix is generated from the
spec map, so the document the implementation team builds against cannot drift from the tests."""

from __future__ import annotations

import re

import pytest
from support.repo import REPO_ROOT, read
from support.spec import SSE_EVENTS
from support.specs import available
from support.specs.map import render_appendix

pytestmark = pytest.mark.hygiene

BEGIN = "<!-- appendix:begin (generated by support.specs.map.render_appendix; do not edit) -->"
END = "<!-- appendix:end -->"
MARKERS = (
    "unit",
    "integration",
    "graph",
    "security",
    "e2e",
    "hygiene",
    "eval",
    "gpu",
    "slow",
    "defect",
    "network",
    "live",
    "pending",
    "selfcheck",
)


def appendix_in_doc() -> str:
    text = read("docs/testing.md")
    match = re.search(re.escape(BEGIN) + r"\n(.*?)\n" + re.escape(END), text, re.S)
    assert match, "docs/testing.md lacks the generated appendix block"
    return match.group(1).strip()


class TestTestingDocument:
    def test_the_document_exists(self) -> None:
        assert (REPO_ROOT / "docs" / "testing.md").is_file()

    def test_the_appendix_matches_the_spec_map(self) -> None:
        assert appendix_in_doc() == render_appendix().strip(), (
            "docs/testing.md is stale: regenerate the appendix from support.specs.map.render_appendix()"
        )

    def test_every_marker_is_documented(self) -> None:
        text = read("docs/testing.md")
        missing = [marker for marker in MARKERS if f"`{marker}`" not in text]
        assert not missing, f"undocumented markers: {missing}"

    def test_every_marker_is_registered_in_pyproject(self) -> None:
        pyproject = read("pyproject.toml")
        missing = [marker for marker in MARKERS if f'"{marker}:' not in pyproject]
        assert not missing, f"unregistered markers: {missing}"

    def test_the_document_explains_the_pending_and_drift_workflow(self) -> None:
        text = read("docs/testing.md")
        assert "PENDING" in text and "DRIFT" in text and "RAGASSIST_STRICT_PENDING" in text


class TestSseContractDocument:
    def test_the_contract_document_lists_every_event_once_the_assistant_api_exists(self) -> None:
        if not available("assistant.sse_stream"):
            pytest.skip(
                "PENDING: the assistant API is not written yet, so the SSE contract is not due"
            )
        path = REPO_ROOT / "docs" / "api" / "sse-contract.md"
        assert path.is_file(), "AGENTS.md section 4.4: API changes need docs/api/sse-contract.md"
        text = path.read_text(encoding="utf-8")
        missing = [
            event for event in SSE_EVENTS if f"`{event}`" not in text and f"{event}" not in text
        ]
        assert not missing, f"sse-contract.md does not document: {missing}"


class TestOpenApiSnapshot:
    def test_the_openapi_snapshot_exists_once_the_assistant_api_exists(self) -> None:
        if not available("assistant.sse_stream"):
            pytest.skip(
                "PENDING: the assistant API is not written yet, so the OpenAPI snapshot is not due"
            )
        assert (REPO_ROOT / "docs" / "api" / "openapi.json").is_file()
