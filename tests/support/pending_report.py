"""Pytest plugin hooks that turn the run into two living reports under ``reports/``:

* ``reports/pending.md``: every suite skipped because planned code is missing (PENDING) or does not
  match the planned interface (DRIFT), grouped by module. This is the implementation team's to-do
  list, and the place where DRIFT shows up before CI turns it into a failure.
* ``reports/defects.md``: every registered defect, with the number of tests that assert it.

The hooks are registered by importing them into ``tests/conftest.py``.
"""

from __future__ import annotations

import re
from collections import defaultdict
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from support.defects import render_markdown as render_defects
from support.repo import REPO_ROOT

REPORTS_DIR: Path = REPO_ROOT / "reports"
_STATUS = re.compile(r"(PENDING|DRIFT): (.*)")
_SKIPS: dict[tuple[str, str], str] = {}
_DEFECTS: dict[str, set[str]] = defaultdict(set)


def _text(longrepr: Any) -> str:
    if isinstance(longrepr, tuple) and len(longrepr) == 3:
        return str(longrepr[2])
    return str(longrepr)


def _record(nodeid: str, text: str) -> None:
    match = _STATUS.search(text)
    if match:
        _SKIPS[(nodeid, match.group(0))] = match.group(0)


def pytest_collectreport(report: Any) -> None:
    if report.skipped:
        _record(report.nodeid, _text(report.longrepr))


def pytest_runtest_logreport(report: Any) -> None:
    if report.skipped and not hasattr(report, "wasxfail"):
        _record(report.nodeid, _text(report.longrepr))


def pytest_collection_finish(session: Any) -> None:
    for item in session.items:
        for mark in item.iter_markers(name="xfail"):
            reason = str(mark.kwargs.get("reason", ""))
            match = re.match(r"(DEFECT-\d+):", reason)
            if match:
                _DEFECTS[match.group(1)].add(item.nodeid)


def render_pending(entries: Iterable[tuple[str, str]]) -> str:
    by_module: dict[str, list[str]] = defaultdict(list)
    for nodeid, reason in entries:
        by_module[nodeid.split("::", 1)[0]].append(reason)
    lines = [
        "# Pending and drifting suites",
        "",
        "PENDING: the planned code does not exist yet (or needs an optional dependency). "
        "DRIFT: the code exists but does not match the planned interface (fix the map or the test). "
        "Generated by `tests/support/pending_report.py`.",
        "",
    ]
    if not by_module:
        lines.append("Nothing pending in this run.")
    for module in sorted(by_module):
        lines.append(f"## {module}")
        for reason in sorted(set(by_module[module])):
            lines.append(f"- {reason}")
        lines.append("")
    return "\n".join(lines) + "\n"


def pytest_terminal_summary(terminalreporter: Any, exitstatus: int, config: Any) -> None:
    REPORTS_DIR.mkdir(exist_ok=True)
    pending = render_pending(_SKIPS.keys())
    (REPORTS_DIR / "pending.md").write_text(pending, encoding="utf-8", newline="\n")
    defects = render_defects({key: sorted(value) for key, value in _DEFECTS.items()})
    (REPORTS_DIR / "defects.md").write_text(defects, encoding="utf-8", newline="\n")
    terminalreporter.write_line(f"reports written to {REPORTS_DIR}: pending.md, defects.md")
