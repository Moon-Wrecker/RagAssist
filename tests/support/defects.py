"""Registry of known defects in the implementation.

A test that asserts the *specified* behaviour but fails against today's code is marked with
``@defect("DEFECT-nn")``: a strict xfail. When the implementation team fixes the bug the test turns
into an unexpected pass (XPASS, strict -> failure), which tells us to delete the marker.

    pytest -m defect              # list open defects
    pytest -m defect --runxfail   # show how each one fails
"""

from __future__ import annotations

from collections.abc import Callable, Iterable, Mapping
from typing import Any, TypeVar

import pytest

F = TypeVar("F", bound=Callable[..., Any])

DEFECTS: dict[str, str] = {}


def defect(defect_id: str, *, strict: bool = True) -> Callable[[F], F]:
    """Mark a test as an xfail for a registered defect.

    ``strict=True`` (default) turns an unexpected pass into a failure, which is the signal to
    remove the marker. Use ``strict=False`` only for tests against nondeterministic real models.
    """
    if defect_id not in DEFECTS:
        raise KeyError(f"Unregistered defect id {defect_id!r}; add it to support/defects.py")

    def decorate(func: F) -> F:
        func = pytest.mark.defect(func)
        return pytest.mark.xfail(strict=strict, reason=f"{defect_id}: {DEFECTS[defect_id]}")(func)

    return decorate


def defect_marks(defect_id: str, *, strict: bool = True) -> list[pytest.MarkDecorator]:
    """Same as :func:`defect` but as marks, for ``pytest.param(..., marks=defect_marks("DEFECT-nn"))``."""
    if defect_id not in DEFECTS:
        raise KeyError(f"Unregistered defect id {defect_id!r}; add it to support/defects.py")
    return [
        pytest.mark.defect,
        pytest.mark.xfail(strict=strict, reason=f"{defect_id}: {DEFECTS[defect_id]}"),
    ]


def render_markdown(occurrences: Mapping[str, Iterable[str]] | None = None) -> str:
    """The defect report: every registered defect and how many tests assert it in this run."""
    seen = {key: sorted(set(value)) for key, value in (occurrences or {}).items()}
    lines = [
        "# Known defects",
        "",
        "Generated by `tests/support/pending_report.py`. Each defect is a strict xfail: when the "
        "implementation is fixed, its test starts passing, the run reports XPASS, and the marker and "
        "registry entry are removed.",
        "",
        "| ID | Specified behaviour that the code violates | Tests asserting it |",
        "|---|---|---|",
    ]
    for defect_id in sorted(DEFECTS):
        tests = seen.get(defect_id, [])
        cell = f"{len(tests)} test(s)" if tests else "**none in this run**"
        lines.append(f"| {defect_id} | {DEFECTS[defect_id]} | {cell} |")
    return "\n".join(lines) + "\n"
